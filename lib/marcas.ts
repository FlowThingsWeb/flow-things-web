/** El nombre de la marca, en formato de URL: "Hey! Beauty" → "hey-beauty". */
export function slugMarca(nombre: string): string {
  return nombre
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/** El logo de una marca, o null si todavía no tiene archivo. */
